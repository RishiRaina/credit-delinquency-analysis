def iqr_outlier_summary(series):
    x = series.dropna()
    q1, q3 = x.quantile([0.25, 0.75])
    iqr = q3 - q1
    lower = q1 - 1.5 * iqr
    upper = q3 + 1.5 * iqr
    outliers = (x < lower) | (x > upper)

    return pd.Series({
        "Lower fence": lower,
        "Upper fence": upper,
        "Potential outlier count": outliers.sum(),
        "Potential outlier percent": 100 * outliers.mean()
    })

